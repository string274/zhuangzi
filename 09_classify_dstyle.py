df = pd.DataFrame(
    raw_data, columns=["编号", "篇名", "PPL", "余弦距离", "Dstyle", "离群比_文本"]
)

# 提取离群比浮点数 (例如 "2/8 (25.0%)" -> 0.25)
df["离群比"] = (
    df["离群比_文本"].str.extract(r"\(([\d\.]+)%\)")[0].astype(float) / 100.0
)

# 判定规则
D_CRIT = 2.487


def classify(row):
    dstyle = row["Dstyle"]
    ratio = row["离群比"]

    if dstyle < D_CRIT and ratio <= 0.30:
        return "类型Ⅰ: 与内篇较接近"
    elif dstyle >= D_CRIT and 0.30 < ratio <= 0.60:
        return "类型Ⅱ: 局部接近、整体偏离"
    elif dstyle >= D_CRIT and ratio > 0.60:
        return "类型Ⅲ: 整体明显偏离"
    else:
        return "类型Ⅳ: 篇内异质性明显"


df["分类结果"] = df.apply(classify, axis=1)

output_df = df[["编号", "篇名", "PPL", "余弦距离", "Dstyle", "离群比_文本", "分类结果"]]
output_df = output_df.rename(columns={"离群比_文本": "离群比"})

